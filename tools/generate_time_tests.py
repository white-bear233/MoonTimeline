"""Turn committed official OTIO vectors into portable MoonBit blackbox tests."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    data = json.loads((ROOT / "fixtures/time_vectors.json").read_text(encoding="utf-8"))
    assert data["otio_version"] == "0.18.1"
    lines = ["// Generated by tools/generate_time_tests.py; expectations come from OTIO.",
             "", "///|", "fn assert_near(actual : Double, expected : Double) -> Unit raise {",
             "  assert_true((actual - expected).abs() <= 1.0e-12 * (1.0 + expected.abs()))", "}"]
    for index, case in enumerate(data["cases"]):
        v, r, target, seconds, converted = (repr(float(case[key])) for key in
            ["value", "rate", "target_rate", "seconds", "rescaled_value"])
        lines += ["", "///|", f'test "OTIO vector {index:03d}" {{',
                  f"  let time = @time.RationalTime::new({v}, {r}).unwrap()",
                  f"  assert_near(time.to_seconds().unwrap(), {seconds})",
                  f"  let converted = time.rescaled_to({target}).unwrap()",
                  f"  assert_near(converted.value(), {converted})",
                  f"  assert_eq(converted.rate(), {target})",
                  f"  let restored = converted.rescaled_to({r}).unwrap()",
                  f"  assert_near(restored.value(), {v})", "}"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "time/oracle_test.mbt"
    expected = render()
    if args.check:
        if path.read_text(encoding="utf-8") != expected:
            raise SystemExit("Generated tests differ; regenerate and review")
        print("Generated OTIO tests verified")
    else:
        path.write_text(expected, encoding="utf-8", newline="\n")
