"""Original deterministic vectors evaluated by pinned official OTIO."""
from pathlib import Path
import json, random
import opentimelineio as o
assert o.__version__ == '0.18.1'
root = Path(__file__).resolve().parents[1]
rt = o.opentime.RationalTime
tr = o.opentime.TimeRange
tt = o.opentime.TimeTransform
rng = random.Random(20261027)
lines = ['// Generated by tools/generate_opentime_tests.py using official OTIO 0.18.1.']
def f(v): return repr(float(v))
rates=[24,25,30,48,50,60,24000/1001,30000/1001,60000/1001]
for i in range(80):
    rate=rng.choice(rates); value=rng.choice([0,1,1798,1800,17982,107892,2589408,rng.randint(0,10000000)])
    t=rt(value,rate); drop=rng.choice([False,None])
    tc=t.to_timecode(rate,drop)
    parsed=rt.from_timecode(tc,rate)
    lines += ['', '///|', f'test "official timecode {i}" {{',
              f'  let t = @time.RationalTime::new({f(value)}, {f(rate)}).unwrap()',
              f'  assert_eq(t.to_timecode(drop_frame={"None" if drop is None else "Some(false)"}).unwrap(), {json.dumps(tc)})',
              f'  near(@time.from_timecode({json.dumps(tc)}, {f(rate)}).unwrap().value(), {f(parsed.value)})', '}']
for i in range(30):
    rate=rng.choice(rates);other=rt(rng.randint(-100,100),rng.choice(rates));offset=rt(rng.randint(-100,100),rate);scale=rng.choice([.5,2,-1,0])
    t=tt(offset,scale,rate); expected=t.applied_to(other)
    lines += ['', '///|', f'test "official transform {i}" {{',
              f'  let t = @transform.TimeTransform::new(offset=@time.RationalTime::new({f(offset.value)}, {f(offset.rate)}).unwrap(), scale={f(scale)}, rate={f(rate)}).unwrap()',
              f'  let r = t.apply_time(@time.RationalTime::new({f(other.value)}, {f(other.rate)}).unwrap()).unwrap()',
              f'  near(r.value(), {f(expected.value)})', f'  near(r.rate(), {f(expected.rate)})','}']
for i in range(30):
    a=tr(rt(rng.randint(0,10),24),rt(rng.randint(1,10),24));b=tr(rt(rng.randint(0,10),24),rt(rng.randint(1,10),24))
    lines += ['', '///|', f'test "official interval relations {i}" {{',
              f'  let a = span({f(a.start_time.to_seconds())}, {f(a.duration.to_seconds())})',
              f'  let b = span({f(b.start_time.to_seconds())}, {f(b.duration.to_seconds())})']
    for name in ['contains','overlaps','before','meets','begins','finishes','intersects']:
        lines += [f'  assert_eq(a.relates(b, @range.{name.capitalize()}), {str(getattr(a,name)(b)).lower()})']
    lines += ['}']
(root/'conformance/opentime_test.mbt').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
